/** Isolated browser smoke with the compiled JAR. Portal auth and IdP are simulated. */
import { pathToFileURL } from 'node:url';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
const librechat = process.env.LIBRECHAT_FIXTURE_ROOT;
if(!librechat) throw new Error('Set LIBRECHAT_FIXTURE_ROOT');
const {chromium} = await import(pathToFileURL(path.join(librechat,'node_modules/playwright/index.mjs')).href);
const output=path.resolve('target/keycloak-portal-local/browser');mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true, channel:process.env.PLAYWRIGHT_CHANNEL ?? "chrome"});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror', e=>errors.push(e.message));
const origin='http://127.0.0.1:33419';
const evidence=[];
const capture=async(name)=>page.screenshot({path:path.join(output,`${name}.png`),fullPage:true});
try {
 await page.goto(`${origin}/portal/data`);
 await page.getByText('Authenticate personal workspace',{exact:true}).first().waitFor();
 assert.equal(await page.locator('iframe').count(),0); evidence.push('No iframe before verified personal login');
 await capture('01-before-login');
 await page.getByRole('link',{name:'Authenticate personal workspace'}).click();
 await page.getByRole('link',{name:'user-a',exact:true}).click();
 await page.waitForURL(`${origin}/portal/data`);
 await page.locator('iframe').waitFor();
 const response=await context.request.get(`${origin}/metabase/auth/keycloak/status`);
 assert.equal(response.status(),200); assert.equal((await response.json()).subject,'user-a');
 const frame=page.frameLocator('iframe');
 await frame.locator('body').waitFor();
 await frame.locator('nav').first().waitFor({timeout:30000});
 evidence.push('Top-level PKCE callback returns to portal; user-a identity verified; full native workspace loaded in same-origin frame');
 await capture('02-user-a-workspace');
 const api=async(route,method='GET',data,headers={})=>context.request.fetch(`${origin}/metabase${route}`,{method,data,headers});
 const me=await (await api('/api/user/current')).json();
 assert.equal(me.is_superuser,false); assert.ok(me.personal_collection_id);
 const databases=await (await api('/api/database')).json();
 const database=(databases.data??databases)[0].id;
 const query={database,type:'native',native:{query:'SELECT 42 AS ANSWER', 'template-tags':{}}};
 const result=await api('/api/dataset','POST',query);
 assert.equal(result.status(),202); assert.deepEqual((await result.json()).data.rows,[[42]]);
 const saved=await api('/api/card','POST',{name:'Fixture personal answer',display:'table',dataset_query:query,visualization_settings:{},collection_id:me.personal_collection_id});
 assert.equal(saved.status(),200); const card=await saved.json();
 const exported=await api(`/api/card/${card.id}/query/csv`,'POST',{});
 assert.equal(exported.status(),200); assert.match(await exported.text(),/42/);
 const child=page.frames().find(f=>f.url().startsWith(`${origin}/metabase/`));
 await child.goto(`${origin}/metabase/question/${card.id}`);
 await frame.getByText('Fixture personal answer',{exact:true}).first().waitFor();
 await child.goto(child.url());
 await frame.getByText('Fixture personal answer',{exact:true}).first().waitFor();
 await capture('03-saved-question-refresh');
 evidence.push('Ordinary user-a queries sample database, saves in personal collection, exports CSV and refreshes saved question through proxy');
 const oldCookie=(await context.cookies()).find(c=>c.name==='metabase.SESSION'); assert.ok(oldCookie);
 await page.getByRole('link',{name:'Portal B',exact:true}).click();
 await page.getByRole('link',{name:'Authenticate personal workspace'}).waitFor();
 await page.waitForFunction(()=>document.querySelectorAll('iframe').length===0);
 evidence.push('Portal account B refuses stale Metabase account A before SSO'); await capture('04-account-mismatch');
 await page.getByRole('link',{name:'Authenticate personal workspace'}).click();
 await page.getByRole('link',{name:'user-b',exact:true}).click();
 await page.waitForURL(`${origin}/portal/data`); await page.locator('iframe').waitFor();
 assert.equal((await (await api('/auth/keycloak/status')).json()).subject,'user-b');
 const denied=await api(`/api/card/${card.id}`); assert.equal(denied.status(),403);
 assert.equal((await api(`/api/card/${card.id}/query/csv`,'POST',{})).status(),403);
 assert.equal((await api('/api/user/current','GET',undefined,{'X-Metabase-Session':oldCookie.value})).status(),401);
 evidence.push('User-b cannot read/export user-a personal card; account switch invalidates previous browser session');
 await frame.getByText(/user-b/).first().waitFor(); await capture('05-user-b-workspace');
 assert.equal((await context.request.get(`${origin}/fixture/revoke`)).status(),200);
 assert.equal((await api('/api/user/current')).status(),401);
 await page.reload();await page.getByRole('link',{name:'Authenticate personal workspace'}).waitFor();
 assert.equal(await page.locator('iframe').count(),0);
 evidence.push('Signed back-channel logout immediately rejects direct API and removes frame on next status check');
 await page.getByRole('link',{name:'Authenticate personal workspace'}).click(); await page.getByRole('link',{name:'user-b',exact:true}).click();
 await page.waitForURL(`${origin}/portal/data`);await page.locator('iframe').waitFor();
 await page.getByRole('button',{name:'Sign out of portal'}).click();await page.waitForURL(`${origin}/portal/data`);
 assert.equal((await api('/api/user/current')).status(),401); assert.equal(await page.locator('iframe').count(),0);
 evidence.push('Portal signout clears local session before simulated IdP/portal logout');
 const unbound=await context.newPage(); await unbound.goto(`${origin}/metabase/auth/keycloak/login`);
 const rejected=unbound.waitForResponse(r=>r.url().includes('/auth/keycloak/callback'));
 await unbound.getByRole('link',{name:'unbound',exact:true}).click(); assert.equal((await rejected).status(),403);
 assert.match(await unbound.locator('body').innerText(),/not bound/); await unbound.close(); evidence.push('Unbound OIDC identity rejected without automatic user creation');
 const blocked=await context.newPage();const csp=[];blocked.on('console',m=>{if(m.type()==='error')csp.push(m.text())});
 await blocked.route('http://127.0.0.1:33421/frame-test',r=>r.fulfill({contentType:'text/html',body:`<iframe src="${origin}/metabase/"></iframe>`}));
 await blocked.goto('http://127.0.0.1:33421/frame-test');
 await blocked.waitForFunction(()=>document.querySelector('iframe').contentDocument===null);
 for(let i=0;i<30 && !blocked.frames().some(f=>f.url().startsWith('chrome-error://'));i++) await new Promise(resolve=>setTimeout(resolve,100));
 const headers=(await context.request.get(`${origin}/metabase/`)).headers();
 assert.equal(headers['x-frame-options'],'SAMEORIGIN'); assert.match(headers['content-security-policy'],/frame-ancestors 'self'/);
 assert.ok(blocked.frames().some(f=>f.url().startsWith('chrome-error://')),`Blocked frame URLs: ${blocked.frames().map(f=>f.url()).join(',')}`);
 await blocked.close(); evidence.push('Different-origin iframe rejected by actual browser CSP/SAMEORIGIN headers');
 assert.equal(errors.length,0);
 writeFileSync(path.join(output,'smoke.json'),JSON.stringify({evidence,pageErrors:errors},null,2));
} catch(e) { await capture('failure'); console.log('Failure page:',page.url(),(await page.locator('body').innerText()).slice(0,1200)); console.log('Page errors:',errors); throw e; } finally {await browser.close();}
